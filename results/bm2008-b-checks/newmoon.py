# Meeus, Astronomical Algorithms 2nd ed., ch. 49 (new moon), used as an independent check of Table S2 Ti.
import math
def jde_newmoon(k):
    T = k/1236.85
    JDE = (2451550.09766 + 29.530588861*k + 0.00015437*T*T - 0.000000150*T**3 + 0.00000000073*T**4)
    E = 1 - 0.002516*T - 0.0000074*T*T
    d = math.radians
    M  = d(2.5534 + 29.10535670*k - 0.0000014*T*T - 0.00000011*T**3)
    Mp = d(201.5643 + 385.81693528*k + 0.0107582*T*T + 0.00001238*T**3 - 0.000000058*T**4)
    F  = d(160.7108 + 390.67050284*k - 0.0016118*T*T - 0.00000227*T**3 + 0.000000011*T**4)
    Om = d(124.7746 - 1.56375588*k + 0.0020672*T*T + 0.00000215*T**3)
    s = math.sin
    corr = (-0.40720*s(Mp) + 0.17241*E*s(M) + 0.01608*s(2*Mp) + 0.01039*s(2*F) + 0.00739*E*s(Mp-M)
            -0.00514*E*s(Mp+M) + 0.00208*E*E*s(2*M) - 0.00111*s(Mp-2*F) - 0.00057*s(Mp+2*F)
            +0.00056*E*s(2*Mp+M) - 0.00042*s(3*Mp) + 0.00042*E*s(M+2*F) + 0.00038*E*s(M-2*F)
            -0.00024*E*s(2*Mp-M) - 0.00017*s(Om) - 0.00007*s(Mp+2*M) + 0.00004*s(2*Mp-2*F)
            +0.00004*s(3*M) + 0.00003*s(Mp+M-2*F) + 0.00003*s(2*Mp+2*F) - 0.00003*s(Mp+M+2*F)
            +0.00003*s(Mp-M+2*F) - 0.00002*s(Mp-M-2*F) - 0.00002*s(3*Mp+M) + 0.00002*s(4*Mp))
    A = [299.77+0.107408*k-0.009173*T*T, 251.88+0.016321*k, 251.83+26.651886*k, 349.42+36.412478*k,
         84.66+18.206239*k, 141.74+53.303771*k, 207.14+2.453732*k, 154.84+7.306860*k, 34.52+27.261239*k,
         207.19+0.121824*k, 291.34+1.844379*k, 161.72+24.198154*k, 239.56+25.513099*k, 331.55+3.592518*k]
    co = [0.000325,0.000165,0.000164,0.000126,0.000110,0.000062,0.000060,0.000056,0.000047,0.000042,0.000040,0.000037,0.000035,0.000023]
    corr += sum(c*math.sin(math.radians(a)) for c,a in zip(co,A))
    return JDE + corr
def jd_to_julian_cal(jd):
    # Meeus ch. 7, Julian calendar (no Gregorian switch)
    jd += 0.5; Z = math.floor(jd); Fr = jd - Z; A = Z
    B = A + 1524; C = math.floor((B-122.1)/365.25); D = math.floor(365.25*C); Ee = math.floor((B-D)/30.6001)
    day = B - D - math.floor(30.6001*Ee) + Fr
    month = Ee-1 if Ee<14 else Ee-13
    year = C-4716 if month>2 else C-4715
    return year, month, day
