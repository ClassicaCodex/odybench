import sys, re
T = r"C:\Projects\odybench\data\text"
def load(name):
    d = {}
    with open(T + "/" + name + ".tsv", encoding="utf-8") as f:
        for ln in f:
            ln = ln.rstrip("\n")
            if "\t" not in ln: continue
            k, v = ln.split("\t", 1)
            k = re.sub(r"^urn:cts:[^:]+:[^:]+\.[^.]+\.[^.]+\.", "", k)
            d[k] = v
    return d
def show(name, refs):
    d = load(name)
    print(f"===== {name}")
    for r in refs:
        if "-" in r:
            a, b = r.split("-")
            pre = a.rsplit(".", 1)[0] + "." if "." in a else ""
            lo = int(a.rsplit(".", 1)[-1]); hi = int(b)
            keys = [f"{pre}{i}" for i in range(lo, hi + 1)]
        else:
            keys = [r]
        for k in keys:
            print(f"{k}\t{d.get(k, '<<MISSING>>')}")
        print("--")
